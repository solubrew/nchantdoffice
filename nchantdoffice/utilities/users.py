from os.path import dirname, join
import datetime as dt

# ======================================3rd Party Library Modules=====================================================||

# ======================================Solutions Brewer Library Modules==============================================||
from kahndor import kahndor
from nchantrs.utilities.users import NchantdUser
from kahndor.logma import Logma
from nchantdoffice.utilities.user_config import (
    get_user_uuid,
    set_user_uuid,
)

# ====================================================================================================================||
here = join(dirname(__file__), "")
log = True
logma = Logma(__name__)

# ====================================================================================================================||
pxcfg = join(here, "_data_", "users.yaml")


class NchantdOfficeUser(NchantdUser):
    """NchantdUser subclass with persist_uuid() integration.

    T-NEW-042 (DESK-0): properly integrated into the desktop
    user flow. Previously defined but never instantiated;
    the inherited ``self.uuid = str(uuid7())`` was discarded
    on every launch.

    The new ``persist_uuid()`` method reads the persisted
    UUID from user_config if present, otherwise generates a
    fresh one and persists it. This guarantees the same
    UUID is used across launches on the same machine —
    critical for the server's anti-abuse rules (same-device
    detection) and for the per-install identity that
    ``application_NCD`` was previously hardcoding.

    The previous stub methods (``create_bridge``,
    ``add_api_service``, ``get_available_services``,
    ``connect_to_service``) were intentionally removed in
    T-NEW-042 — they were dead code (never called from
    anywhere) and the parent ``NchantdUser`` already wires
    the secure-store API key flow that they duplicated.
    """

    def __init__(self, parent=None, cfg=None):
        super().__init__(parent, cfg)
        self.config.override(
            kahndor.Instruct(pxcfg).select("NchantdOfficeUser").override(cfg)
        )
        logma.info(
            f"[users] NchantdOfficeUser.__init__ "
            f"parent={type(parent).__name__} cfg_keys={list((cfg or {}).keys())}"
        )

    def persist_uuid(self) -> str:
        """Read the persisted UUID from user_config; if absent,
        persist the UUID generated by the parent NchantdUser.

        Returns:
            The stable per-install UUID (str).

        T-NEW-042 (DESK-0): guarantees the same UUID is used
        across launches on the same machine. The server's
        anti-abuse rules (``is_self_referral``) rely on this
        stability for device-fingerprint matching.
        """
        persisted = get_user_uuid()
        if persisted:
            # Use the persisted one (stable across launches)
            self.uuid = persisted
            logma.info(
                f"[users] persist_uuid: loaded persisted UUID "
                f"({persisted[:8]}...)"
            )
        else:
            # First launch — persist the freshly-generated UUID
            set_user_uuid(self.uuid)
            logma.info(
                f"[users] persist_uuid: persisted fresh UUID "
                f"({self.uuid[:8]}...)"
            )
        return self.uuid


