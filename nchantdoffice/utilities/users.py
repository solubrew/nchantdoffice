# ======================================3rd Party Library Modules=====================================================||

# ======================================Solutions Brewer Library Modules==============================================||
from kahndor import kahndor
from nchantrs.utilities.users import NchantdUser
from kahndor.logma import Logma
from nchantdoffice.utilities.user_config import (
    get_user_uuid,
    set_user_uuid,
)

# ====================================================================================================================||
here = join(dirname(__file__), "")
log = True
logma = Logma(__name__)

# ====================================================================================================================||
pxcfg = join(here, "_data_", "users.yaml")


class NchantdOfficeUser(NchantdUser):
    """NchantdUser subclass with persist_uuid() integration.

    T-NEW-042 (DESK-0): properly integrated into the desktop
    user flow. Previously defined but never instantiated;
    the inherited ``self.uuid = str(uuid7())`` was discarded
    on every launch.

    The new ``persist_uuid()`` method reads the persisted
    UUID from user_config if present, otherwise generates a
    fresh one and persists it. This guarantees the same
    UUID is used across launches on the same machine —
    critical for the server's anti-abuse rules (same-device
    detection) and for the per-install identity that
    ``application_NCD`` was previously hardcoding.

    The previous stub methods (``create_bridge``,
    ``add_api_service``, ``get_available_services``,
    ``connect_to_service``) were intentionally removed in
    T-NEW-042 — they were dead code (never called from
    anywhere) and the parent ``NchantdUser`` already wires
    the secure-store API key flow that they duplicated.
    """

    def __init__(self, parent=None, cfg=None) -> None:
        super().__init__(parent, cfg)
        self.config.override(kahndor.Instruct(pxcfg).select("NchantdOfficeUser").override(cfg))
        logma.info(
            f"[users] NchantdOfficeUser.__init__ " f"parent={type(parent).__name__} cfg_keys={list((cfg or {}).keys())}"
        )
        # T-NEW-141b: derive ``has_pro`` from the local
        # ``DesktopCredentials`` cache (``pycurity`` /
        # ``credentials.load_credentials().user_tier``).
        # The service-truth path (a live ``nchantdoffice.com``
        # call to refresh ``user_tier`` on every boot) is
        # explicitly out of scope; the local cache is what
        # we have. Tier semantics: ``pro`` / ``pro_data`` /
        # ``enterprise`` grant ``has_pro=True``; ``free`` (and
        # missing / malformed creds) default to True to
        # preserve the original hardcoded behaviour.
        self.has_pro = self._resolve_has_pro_from_credentials()
        # DESK T-NEW-140 v6.2: ``has_account`` tracks whether the
        # desktop has successfully registered or claimed an
        # account on the server. It flips to True the moment the
        # local DesktopCredentials cache holds a complete record
        # (server returned both desktop_uuid AND api_key). After
        # that point the Settings tab can route through the
        # server's /user-account/home (which 302s to login if no
        # session cookie, otherwise shows the dashboard) rather
        # than dropping the user back to /registration on every
        # tab reactivation. A clean install has no credentials
        # record → has_account=False → direct to /registration.
        self.has_account = self._resolve_has_account_from_credentials()
        self.easter_egg = None
        self.nchantd_account_wizard_visible = True
        self.nchantd_account_status = False
        self.nchantd_account_credits = 0

    def _create_user(self):
        """"""
        user = super()._create_user()
        return user

    def persist_uuid(self) -> str:
        """Read the persisted UUID from user_config; if absent,
        persist the UUID generated by the parent NchantdUser.

        Returns:
            The stable per-install UUID (str).

        T-NEW-042 (DESK-0): guarantees the same UUID is used
        across launches on the same machine. The server's
        anti-abuse rules (``is_self_referral``) rely on this
        stability for device-fingerprint matching.
        """
        persisted = get_user_uuid()
        if persisted:
            # Use the persisted one (stable across launches)
            self.uuid = persisted
            logma.info(f"[users] persist_uuid: loaded persisted UUID " f"({persisted[:8]}...)")
        else:
            # First launch — persist the freshly-generated UUID
            set_user_uuid(self.uuid)
            logma.info(f"[users] persist_uuid: persisted fresh UUID " f"({self.uuid[:8]}...)")
        return self.uuid

    @staticmethod
    def _resolve_has_pro_from_credentials() -> bool:
        """T-NEW-141b: read the cached ``user_tier`` and map
        it to a pro / free boolean.

        Defensive at every step: any exception, missing
        field, or unparseable value falls back to True
        (the original hardcoded behaviour). The free tier
        has_pro=False path is opt-in -- the user must
        have explicitly stored ``user_tier='free'`` for
        this method to return False.
        """
        try:
            from nchantdoffice.utilities.credentials import (
                load_credentials,
            )

            creds = load_credentials()
        except Exception as exc:
            logma.warning(
                f"[users] _resolve_has_pro_from_credentials: "
                f"load_credentials failed: {exc}; defaulting "
                f"has_pro=True"
            )
            return True
        if creds is None:
            return True
        tier = getattr(creds, "user_tier", None)
        if not tier:
            # Legacy credentials with no user_tier field
            # default to True (matches the pre-141b behaviour).
            return True
        return tier in ("pro", "pro_data", "enterprise")

    @staticmethod
    def _resolve_has_account_from_credentials() -> bool:
        """T-NEW-140 v6.2: True if the desktop has a complete
        DesktopCredentials record on disk.

        ``is_complete()`` is True once the server has returned
        both ``desktop_uuid`` (used for same-device detection) AND
        ``api_key`` (used in the ``x-api-key`` header on every auth
        call). The record is written by the register / claim /
        login flows, so a True here means the desktop has
        successfully established an account on the server at some
        point. The session cookie itself may or may not still be
        valid — the user-account router handles both cases
        (dashboard if logged in, login if not). A clean install has
        no record, so this returns False and the Settings tab routes
        straight to /registration per Option B.

        Defensive: any exception (missing pykey, corrupted file,
        permission error) returns False — better to show the
        registration page than to assume an account exists.
        """
        try:
            from nchantdoffice.utilities.credentials import (
                load_credentials,
            )

            creds = load_credentials()
        except Exception as exc:
            logma.warning(
                f"[users] _resolve_has_account_from_credentials: "
                f"load_credentials failed: {exc}; defaulting has_account=False"
            )
            return False

        if creds is None:
            return False
        return bool(creds.is_complete())


