# ======================================Solutions Brewer Library Modules==============================================||
from kahndor import kahndor
from kahndor.logma import Logma
from nchantrs.widgets.media.editors.editors import NchantdDocEditor

# ====================================================================================================================||
HERE = join(dirname(__file__), "")  # ||
log = True
logma = Logma(__name__)
if not log:
    logma.off()
# ====================================================================================================================||
PXCFG = join(HERE, "_data_", ".yaml")


class NchantdOfficeDocEditor(NchantdDocEditor):
    """"""

    def __init__(self, parent=None, cfg=None):
        super().__init__(parent, cfg)
        self.config.override(kahndor.Instruct(PXCFG).select("Nchantd").override(cfg))

    def initModel(self, cfg=None):
        """"""
        super().initModel(cfg)
        return self

    def initView(self, cfg=None):
        """"""
        super().initView(cfg)
        return self

    def initWidget(self, cfg=None):
        """"""
        self.initModel(cfg)
        self.initView(cfg)
        return self

    def focusOutEvent(self, event=None, *args, **kwargs):
        super().focusOutEvent(event, args, kwargs)
        logma.info(f"Focus Out")
        handler = self.config.get("focus_out_handler", None)
        if handler:
            handler()
        return self


