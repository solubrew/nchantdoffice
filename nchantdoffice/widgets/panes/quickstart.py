# ====================================================================================================================||
here = join(dirname(__file__), "")  # ||
log = True
logma = Logma(__name__)

# ====================================================================================================================||
pxcfg = join(here, "_data_", ".yaml")


class NchantdQuickStartPane(NchantdPane):
    """
    show a list of links for basic interactions
    when clicked launch a tab under the help node with structured nodes and tabs
    this way the user gets the help but only what they ask for easier revisiting
    """

    def __init__(self, parent=None, cfg=None):
        """ """
        super().__init__(parent, cfg)
        self.parent = parent
        self.config.override(kahndor.Instruct(pxcfg).select("NchantdQuickStartPane"))
        if self.parent:
            self.config.override(parent.config)
        self.config.override(cfg)

    def initModel(self, cfg=None):
        """"""
        super().initModel(cfg)
        return self

    def initView(self, cfg=None):
        """"""
        super().initView(cfg)
        cfg = {}
        self.links = NchantdTreeList(self, cfg).initWidget()
        self.layout.addWidget(self.links)
        return self

    def initWidget(self):
        """"""
        self.initModel()
        self.initView()
        return self


