# ====================================================================================================================||
here = join(dirname(__file__), "")  # ||
log = True
logma = Logma(__name__)

# ====================================================================================================================||
pxcfg = join(here, "_data_", "weather.yaml")


class NchantdWeatherPane(NchantdPane):
    """"""

    def __init__(self, parent=None, cfg=None):
        """ """
        self.parent = parent
        self.config = condor.Instruct(pxcfg).select("NchantdWeatherPane")
        if self.parent:
            self.config.override(parent.config)
        super().__init__(self)
        self.config.override(cfg)
        self.html = self.config.dikt.get("html")

    def initModel(self):
        """"""
        super().initModel()
        city = self.config.dikt.get("city")
        apiKey = self.config.dikt.get("apiKey")
        url = f"`https://api.openweathermap.org/data/2.5/weather?q=${city}&appid=${apiKey}&units=metric`"
        self.html = self.html.replace("<[url]>", url)
        return self

    def initView(self):
        """"""
        super().initView()
        return self

    def initWidget(self):
        """"""
        self.initModel()
        self.initView()
        return self


