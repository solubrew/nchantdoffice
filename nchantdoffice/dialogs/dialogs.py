class NchantdOfficeDocumentCape(NchantdCape):
    """"""

    def __init__(self, name, instance=None, parent=None, cfg=None, args=None):
        """ """
        self.parent = parent
        self.config = condor.Instruct(pxcfg).select("NchantdOfficeDocumentCape")
        if self.parent:
            self.config.override(parent.config)
        super().__init__(name, instance, self.parent, self.config, args)
        self.config.override(cfg)
        self.is_installable = True

    def initModel(self):
        """"""
        super().initModel()
        self.model.pybook = PyfficeBook()
        return self

    def initView(self, cfg=None):
        """"""
        super().initView(cfg)
        return self

    def initWidget(self):
        """"""
        self.initModel()
        self.initView()
        return self


